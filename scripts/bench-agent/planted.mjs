/**
 * The code of the defects the find-the-bug questions plant, and of their
 * twins (P392). What is a defect and what a twin is said by the model
 * (`plantDefects` in `model.mjs`) and written into the key from there; this
 * writes only the files, by repository, each with the class a module
 * registers where one does (`register`: a controller or a provider).
 */

const lines = (...parts) => `${parts.flat().join('\n')}\n`;

const gatewayImports = [
  `import { Injectable } from '@nestjs/common';`,
  `import { HttpService } from '@nestjs/axios';`,
  `import { ConfigService } from '@nestjs/config';`,
  `import { firstValueFrom } from 'rxjs';`,
];

const clientHead = (className, what) => [
  ...gatewayImports,
  '',
  `/** ${what}, as the gateway asks for them. */`,
  '@Injectable()',
  `export class ${className} {`,
  '  constructor(',
  '    private readonly http: HttpService,',
  '    private readonly config: ConfigService,',
  '  ) {}',
  '',
];

/** One request on from the gateway, answered with its body. */
const send = (verb, env, path, body) =>
  `    return firstValueFrom(this.http.${verb}<unknown>(\`\${this.config.get('${env}')}${path}\`${body === undefined ? '' : `, ${body}`})).then((answer) => answer.data);`;

